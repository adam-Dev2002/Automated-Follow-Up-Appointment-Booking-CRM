        assert.ok(visibleHistory.includes('Signed in'));
        assert.equal(visibleHistory.includes('session.login'), false);
        assert.equal(visibleHistory.includes('appointment.book'), false);
        assert.equal(visibleHistory.includes(signedSession.user.id), false);
        assert.equal(await page.locator('#audit-rows pre').count(), 0);
        const bookingDetails = page.locator('#audit-rows tr').filter({ hasText: 'Created a booking' }).first();
        await bookingDetails.locator('summary').click();
        assert.ok((await bookingDetails.locator('.audit-change-list').innerText()).includes('Service'));
        assert.equal((await bookingDetails.innerText()).includes('2030-01-01T01:00:00.000Z'), false);
        fs.mkdirSync(path.resolve(__dirname, '../.local/verification'), { recursive: true });
        await page.locator('#workspace-account-modal .modal-content').screenshot({ path: path.resolve(__dirname, '../.local/verification/workspace-accounts-desktop.png'), animations: 'disabled' });
