        assert.ok(audit.events.some(e => e.actor_role === 'staff' && e.action === 'appointment.book'));
        assert.equal(JSON.stringify(audit).includes('isolated-staff-password'), false);
        await page.locator('#audit-reference').fill('appt_isolated_1');
