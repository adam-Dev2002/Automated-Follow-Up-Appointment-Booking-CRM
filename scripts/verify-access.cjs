        await page.locator('#accounts-tab').click();
        await page.locator('[data-account="' + staff.id + '"][data-change="disabled"]').click();
        await page.locator('#account-confirm-modal').waitFor({ state: 'visible' });
        await page.locator('#account-confirm-submit').click();
        await page.locator('#account-confirm-modal').waitFor({ state: 'hidden' });
        await page.locator('#workspace-account-modal').waitFor({ state: 'visible' });
        assert.equal((await staffContext.request.get(fixture.base + '/api/users')).status(), 401);
